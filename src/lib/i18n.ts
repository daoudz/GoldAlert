export type TranslationKey = keyof (typeof STRINGS)['en'];

export function tr(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const table = STRINGS[lang] ?? STRINGS.en;
  let s: string = (table as Record<string, string>)[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

const currencyNameCache = new Map<string, string>();

export function currencyName(code: string, fallback: string, lang: Lang = 'en'): string {
  if (lang === 'en') return fallback;
  const key = `${lang}|${code}`;
  const cached = currencyNameCache.get(key);
  if (cached) return cached;
  try {
    const dn = new Intl.DisplayNames([lang], { type: 'currency' }).of(code);
    const res = dn && dn !== code ? dn : fallback;
    currencyNameCache.set(key, res);
    return res;
  } catch {
    return fallback;
  }
}

